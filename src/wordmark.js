const NS = 'http://www.w3.org/2000/svg';

// 유리 글자 하나 = (1) 뒤 배경을 흐리게 굴절시키는 backdrop 레이어(clip-path로 글자 모양)
//                 + (2) 가장자리 하이라이트/분산(dispersion)을 그리는 SVG 오버레이
export function buildWordmark(root) {
  const defs = document.createElementNS(NS, 'svg');
  defs.setAttribute('width', '0');
  defs.setAttribute('height', '0');
  defs.setAttribute('aria-hidden', 'true');
  defs.style.position = 'absolute';
  let defsHTML = '<defs>';

  LETTERS.forEach((L) => {
    // objectBoundingBox 단위로 변환해 반응형 크기에서도 정확히 클리핑
    defsHTML += `<clipPath id="clip-${L.key}" clipPathUnits="objectBoundingBox"><path transform="scale(${1 / L.w} ${1 / L.h})" d="${L.d}"/></clipPath>`;
  });
  defsHTML += `
    <linearGradient id="edge-light" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#fff" stop-opacity=".5"/>
      <stop offset=".35" stop-color="#fff" stop-opacity=".16"/>
      <stop offset=".7" stop-color="#fff" stop-opacity=".1"/>
      <stop offset="1" stop-color="#fff" stop-opacity=".3"/>
    </linearGradient>
    <filter id="inner-soft" x="-10%" y="-10%" width="120%" height="120%">
      <feGaussianBlur stdDeviation="1.6"/>
    </filter>
  </defs>`;
  defs.innerHTML = defsHTML;
  root.appendChild(defs);

  LETTERS.forEach((L) => {
    const el = document.createElement('span');
    el.className = 'glyph';
    el.dataset.letter = L.key;
    el.style.left = `${(L.x / WORD_W) * 100}%`;
    el.style.top = `${(L.y / WORD_H) * 100}%`;
    el.style.width = `${(L.w / WORD_W) * 100}%`;
    el.style.height = `${(L.h / WORD_H) * 100}%`;

    const glass = document.createElement('span');
    glass.className = 'glyph__glass';
    glass.style.clipPath = `url(#clip-${L.key})`;
    glass.style.webkitClipPath = `url(#clip-${L.key})`;

    const svg = document.createElementNS(NS, 'svg');
    svg.setAttribute('class', 'glyph__edge');
    svg.setAttribute('viewBox', `0 0 ${L.w} ${L.h}`);
    svg.setAttribute('preserveAspectRatio', 'none');
    svg.innerHTML = `
      <g clip-path="url(#clip-${L.key}-u)">
        <path d="${L.d}" fill="none" stroke="rgba(0,0,0,.3)" stroke-width="5" transform="translate(1.2 1.6)" filter="url(#inner-soft)"/>
        <path d="${L.d}" fill="none" stroke="url(#edge-light)" stroke-width="1.6"/>
      </g>
      <defs><clipPath id="clip-${L.key}-u"><path d="${L.d}"/></clipPath></defs>`;

    el.append(glass, svg);
    root.appendChild(el);
  });

  return root.querySelectorAll('.glyph');
}
